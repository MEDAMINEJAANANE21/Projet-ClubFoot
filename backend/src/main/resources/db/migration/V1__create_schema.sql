create table product (
    id         bigint generated by default as identity primary key,
    name       varchar(120)  not null,
    category   varchar(20)   not null,
    color      varchar(40)   not null,
    price      numeric(10, 2) not null check (price > 0),
    image_url  varchar(255)  not null,
    badge      varchar(40)
);

create table customer_order (
    id               bigint generated by default as identity primary key,
    reference        varchar(30)    not null unique,
    customer_name    varchar(120)   not null,
    customer_email   varchar(160)   not null,
    customer_phone   varchar(30)    not null,
    shipping_address varchar(255)   not null,
    city             varchar(80)    not null,
    status           varchar(20)    not null,
    total            numeric(10, 2) not null,
    created_at       timestamp with time zone not null
);

create table order_line (
    id           bigint generated by default as identity primary key,
    order_id     bigint         not null references customer_order (id) on delete cascade,
    product_id   bigint         not null,
    product_name varchar(120)   not null,
    unit_price   numeric(10, 2) not null,
    quantity     integer        not null check (quantity between 1 and 20)
);

create index idx_order_line_order on order_line (order_id);

create table membership_application (
    id         bigint generated by default as identity primary key,
    full_name  varchar(120) not null,
    birth_date date         not null,
    gender     varchar(10)  not null,
    email      varchar(160) not null,
    phone      varchar(30)  not null,
    address    varchar(255) not null,
    country    varchar(60)  not null,
    status     varchar(20)  not null,
    created_at timestamp with time zone not null
);

create table membership_document (
    membership_id bigint      not null references membership_application (id) on delete cascade,
    document      varchar(30) not null,
    primary key (membership_id, document)
);

create table contact_message (
    id         bigint generated by default as identity primary key,
    name       varchar(120)  not null,
    email      varchar(160)  not null,
    subject    varchar(40)   not null,
    message    varchar(2000) not null,
    is_read    boolean       not null default false,
    created_at timestamp with time zone not null
);
